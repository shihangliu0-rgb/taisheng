/**
 ******************************************************************************
 * @file    pc_link_config.h
 * @brief   小电脑(ROS2 competition_gateway)串口对接 —— 集中配置头
 *
 * 上位机侧协议参考:
 *   src/competition_gateway/config/serial_gateway.yaml
 *   src/competition_gateway/include/competition_gateway/serial_protocol.hpp
 *
 * 所有可调参数都集中在本文件,需要更换串口 / 波特率 / 周期时,
 * 只改本文件的宏即可,无需改动 pc_link.c 模块源码。
 ******************************************************************************
 */
#ifndef PC_LINK_CONFIG_H
#define PC_LINK_CONFIG_H

/* ----------------------------------------------------------------------------
 * 1. 总开关
 *    1 = 启用本模块(占用一个串口)
 *    0 = 完全禁用:pc_link.h 会把所有接口替换为空操作,不占用串口与内存
 * --------------------------------------------------------------------------*/
#define PC_LINK_ENABLE                 1U

/* ----------------------------------------------------------------------------
 * 2. 串口快速切换宏 —— 换串口只改下面这一行
 *
 *    可用空闲串口(引脚 / 中断 / DMA 均已由 CubeMX 配置好):
 *      huart7 : PE7=RX  PE8=TX   MX 默认 115200   ← 默认选择
 *      huart8 : PE0=RX  PE1=TX   MX 默认 2000000(启用本模块时
 *               PcLink_Init() 会按 PC_LINK_BAUD_RATE 自动重配)
 *
 *    已占用,请勿选择:
 *      huart4 : 操作手端上位机无线串口(user/com_link/computer_link.c)
 *      huart1 : IMU, 921600
 *      huart9 : DT35 + PNP 测距传感器
 *      huart2 : 疑似预留遥控器(DMA 环形接收,优先级极高),勿动
 * --------------------------------------------------------------------------*/
#define PC_LINK_UART_HANDLE            huart7
/* #define PC_LINK_UART_HANDLE         huart8 */

/* ----------------------------------------------------------------------------
 * 3. 波特率
 *    必须与小电脑 serial_gateway.yaml 中的 baudrate 保持一致(默认 115200)。
 *    PcLink_Init() 会把宏选中的串口重配为该波特率。
 * --------------------------------------------------------------------------*/
#define PC_LINK_BAUD_RATE              115200U

/* ----------------------------------------------------------------------------
 * 4. 状态帧回传周期(ms)
 *    上位机要求下位机状态帧频率不低于 10Hz(周期 <= 100ms)。
 *    默认 50ms = 20Hz。
 * --------------------------------------------------------------------------*/
#define PC_LINK_STATUS_PERIOD_MS       50U

/* ----------------------------------------------------------------------------
 * 5. 数据超时(ms)
 *    超过该时长未收到某类帧,自动清除对应数据的有效位(不得沿用旧值)。
 *    与上位机 data_timeout_ms(200ms)保持一致。
 * --------------------------------------------------------------------------*/
#define PC_LINK_DATA_TIMEOUT_MS        200U

/* ----------------------------------------------------------------------------
 * 6. 接收环形缓冲区大小(字节)
 *    最大帧为感知帧 44 字节,256 足够(必须为 2 的幂)。
 * --------------------------------------------------------------------------*/
#define PC_LINK_RX_BUFFER_SIZE         256U

#endif /* PC_LINK_CONFIG_H */
